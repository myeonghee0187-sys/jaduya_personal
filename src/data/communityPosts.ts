  hashtag: string;
  /** 분류 chip (베이지 계열) — 정보 / 질문 / 후기 / 잡담 */
  category: string;
  title: string;
  /** 본문 미리보기 — 카드에서 한 줄로 줄임 */
  preview: string;
  /** 게시글 상세보기용 본문 전체 — 아직 일부 게시글에만 있다 (없으면 카드가 안 눌린다) */
